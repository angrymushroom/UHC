-- Load Index documents, download snapshots and service JSONL from the stage root.
-- Recreates raw tables; execute COPY statements after creation. Each statement commits separately.
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS UHC_WH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS UHC_DB;
CREATE SCHEMA IF NOT EXISTS UHC_DB.ANALYTICS;
USE WAREHOUSE UHC_WH;
USE DATABASE UHC_DB;
USE SCHEMA ANALYTICS;

CREATE STAGE IF NOT EXISTS UHC_STAGE;
CREATE OR REPLACE FILE FORMAT UHC_RAW_JSON TYPE = JSON COMPRESSION = GZIP;
CREATE OR REPLACE TABLE RAW_INDEX_INPUT (PAYLOAD VARIANT NOT NULL);
CREATE OR REPLACE TABLE RAW_DOWNLOAD_INPUT (PAYLOAD VARIANT NOT NULL);
CREATE OR REPLACE TABLE RAW_PRICING_INPUT (PAYLOAD VARIANT NOT NULL);

COPY INTO RAW_INDEX_INPUT FROM @UHC_STAGE/indexes.jsonl.gz
    FILE_FORMAT = (FORMAT_NAME = UHC_RAW_JSON) ON_ERROR = ABORT_STATEMENT;
COPY INTO RAW_DOWNLOAD_INPUT FROM @UHC_STAGE/downloads.jsonl.gz
    FILE_FORMAT = (FORMAT_NAME = UHC_RAW_JSON) ON_ERROR = ABORT_STATEMENT;
COPY INTO RAW_PRICING_INPUT FROM @UHC_STAGE/pricing.jsonl.gz
    FILE_FORMAT = (FORMAT_NAME = UHC_RAW_JSON) ON_ERROR = ABORT_STATEMENT;

-- Preserve JSON nulls, original identifiers and exact decimal amounts.
CREATE OR REPLACE FUNCTION UHC_TEXT(v VARIANT) RETURNS VARCHAR LANGUAGE SQL AS
$$ CASE WHEN v IS NULL OR IS_NULL_VALUE(v) THEN NULL ELSE CAST(v AS VARCHAR) END $$;

CREATE OR REPLACE FUNCTION UHC_ID(v VARIANT) RETURNS VARCHAR LANGUAGE SQL AS
$$ CASE WHEN IS_VARCHAR(v) AND LENGTH(CAST(v AS VARCHAR)) > 0 THEN CAST(v AS VARCHAR)
        WHEN (IS_INTEGER(v) OR IS_DECIMAL(v)) AND v = TRUNC(CAST(v AS NUMBER(38, 12)))
             THEN TO_VARCHAR(CAST(v AS NUMBER(38, 0)))
        ELSE TO_VARCHAR(TO_NUMBER(CONCAT('invalid identifier: ', COALESCE(CAST(v AS VARCHAR), 'NULL'))))
   END $$;

CREATE OR REPLACE FUNCTION UHC_AMOUNT(v VARIANT) RETURNS NUMBER(18,6) LANGUAGE SQL AS
$$ CASE WHEN v IS NULL OR IS_NULL_VALUE(v) THEN NULL
        WHEN TRY_TO_DECIMAL(CAST(v AS VARCHAR),18,6) IS NOT NULL
             AND TO_VARIANT(TO_DECIMAL(CAST(v AS VARCHAR),18,6)) = v
             THEN TO_DECIMAL(CAST(v AS VARCHAR),18,6)
        ELSE TO_NUMBER(CONCAT('invalid amount: ', COALESCE(CAST(v AS VARCHAR),'NULL')))
   END $$;
