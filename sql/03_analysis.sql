-- Summarize comparable OHBS service prices for the chart. Rerun after rebuilding base prices.
USE ROLE SYSADMIN;
USE WAREHOUSE UHC_WH;
USE DATABASE UHC_DB;
USE SCHEMA ANALYTICS;

CREATE OR REPLACE TABLE IN_SERVICE_DISPERSION_SQL AS
SELECT FILE_KEY, SOURCE_FILENAME, SERVICE_POSITION,
       BILLING_CODE, NAME AS SERVICE_NAME, EXPIRATION_DATE,
       COUNT(*) AS RATE_RECORDS,
       PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY NEGOTIATED_RATE) AS P25_RATE,
       MEDIAN(NEGOTIATED_RATE) AS MEDIAN_RATE,
       PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY NEGOTIATED_RATE) AS P75_RATE
FROM IN_NETWORK_RATES_SQL
-- Match billing conditions without expanding provider associations.
WHERE SOURCE_FILENAME LIKE '%Optum-Health-Behavioral-Services--OHBS-%'
  AND BILLING_CODE_TYPE = 'CPT' AND BILLING_CODE_TYPE_VERSION = '2026'
  AND NEGOTIATION_ARRANGEMENT = 'ffs' AND NEGOTIATED_TYPE = 'negotiated'
  AND BILLING_CLASS = 'professional' AND SETTING = 'outpatient'
  AND ARRAY_SIZE(SERVICE_CODE) = 1 AND ARRAY_TO_STRING(SERVICE_CODE, ',') = '11'
  AND ARRAY_SIZE(BILLING_CODE_MODIFIER) = 0
  AND ADDITIONAL_INFORMATION = '' AND SEVERITY_OF_ILLNESS = ''
  AND NEGOTIATED_RATE > 0
GROUP BY FILE_KEY, SOURCE_FILENAME, SERVICE_POSITION, BILLING_CODE, NAME, EXPIRATION_DATE
-- Display threshold, not a statistical reliability guarantee.
HAVING COUNT(*) >= 20 AND COUNT(DISTINCT NEGOTIATED_RATE) >= 2;
